"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { Button, Spin, Typography } from "antd";
import Tally from "@/components/Tally";
import { getSettings, listProfiles } from "@/lib/api";
import { pageLede, pageTitle } from "@/lib/ui";

interface Step {
  title: string;
  body: string;
  cta: string;
  href: string;
  /** Known only for steps we can check from the data we already load. */
  done?: boolean;
}

export default function HomePage() {
  const [hasKey, setHasKey] = useState(false);
  const [hasProfile, setHasProfile] = useState(false);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    Promise.all([getSettings(), listProfiles()])
      .then(([settings, profiles]) => {
        setHasKey(settings.falApiKey.trim() !== "");
        setHasProfile(profiles.length > 0);
      })
      .catch(() => {
        /* the steps still read fine without their done marks */
      })
      .finally(() => setReady(true));
  }, []);

  const steps: Step[] = [
    {
      title: "Add your fal.ai key",
      body: "Video is generated by Kling 3.0 through fal.ai, which needs your API key. Without one, profiles can only generate text.",
      cta: "Open settings",
      href: "/settings",
      done: hasKey,
    },
    {
      title: "Create a profile",
      body: "One profile per channel persona. It holds that persona's prompt templates, generations and channels.",
      cta: "Go to profiles",
      href: "/profiles",
      done: hasProfile,
    },
    {
      title: "Write a prompt template and generate",
      body: "Press Generate on a template and the video renders in the background. The Generations tab shows progress.",
      cta: "Go to profiles",
      href: "/profiles",
    },
    {
      title: "Connect YouTube and publish",
      body: "Connect a channel from a profile's Channels tab, then publish any finished video from its row in Generations.",
      cta: "Go to profiles",
      href: "/profiles",
    },
  ];

  // The first step we can see is unfinished gets the spotlight; once both
  // checkable steps are done, it moves on to generating.
  const firstOpen = steps.findIndex((s) => s.done === false);
  const next = firstOpen === -1 ? 2 : firstOpen;

  return (
    <>
      <Typography.Title level={1} style={pageTitle}>
        From prompt to published
      </Typography.Title>
      <Typography.Paragraph type="secondary" style={pageLede}>
        Four steps from an empty account to a video on YouTube.
      </Typography.Paragraph>

      <div style={{ marginTop: 44 }}>
        {!ready ? (
          <div style={{ padding: 48, textAlign: "center" }}>
            <Spin />
          </div>
        ) : (
          <ol className="acmp-steps">
            {steps.map((s, i) => (
              <li
                key={s.title}
                className={
                  s.done
                    ? "acmp-step is-done"
                    : i === next
                      ? "acmp-step is-next"
                      : "acmp-step"
                }
              >
                <div className="acmp-step-num" aria-hidden>
                  {i + 1}
                </div>
                <div>
                  <Typography.Title
                    level={3}
                    style={{ margin: 0, fontSize: 24, fontWeight: 600 }}
                  >
                    {s.title}
                  </Typography.Title>
                  <Typography.Paragraph
                    type="secondary"
                    style={{ margin: "8px 0 18px", maxWidth: "58ch" }}
                  >
                    {s.body}
                  </Typography.Paragraph>
                  {s.done ? (
                    <Tally status="succeeded" />
                  ) : (
                    <Link href={s.href}>
                      <Button type={i === next ? "primary" : "default"}>
                        {s.cta}
                      </Button>
                    </Link>
                  )}
                </div>
              </li>
            ))}
          </ol>
        )}
      </div>
    </>
  );
}
